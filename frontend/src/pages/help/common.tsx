export function errorsSection(): Section {
  return {
    id: "errors",
    title: "Если что-то пошло не так",
    body: (
      <>
        <p>
          Каждое сообщение об ошибке содержит понятную причину и код. Технических подробностей (номеров ответа сервера, адресов) в
          сообщениях нет - они пишутся в журнал сервера. Сообщите код администратору - по нему проблему найдут быстрее.
        </p>
        <table>
          <thead>
            <tr>
              <th>Код</th>
              <th>Что значит</th>
              <th>Что делать</th>
            </tr>
          </thead>
          <tbody>
            {ERRORS.map(([code, meaning, action]) => (
              <tr key={code}>
                <td>
                  {code.split(", ").map((item, index) => (
                    <span key={item}>
                      {index > 0 && ", "}
                      <code>{item}</code>
                    </span>
                  ))}
                </td>
                <td>{meaning}</td>
                <td>{action}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </>
    ),
  };
}
